const { describe, it, before, after } = require('node:test');
const assert = require('node:assert/strict');
const cds = require('@sap/cds');

describe('SAP Cloud Integration (CPI) Connector Simulation Tests', () => {
    let srv;
    let targetInterfaceId;

    before(async () => {
        cds.env.requires.db = { kind: 'sqlite', credentials: { url: 'sentinel.db' } };
        const csn = await cds.load('srv/monitoring-service.cds');
        cds.model = csn;
        await cds.connect.to('db');
        srv = await cds.serve('MonitoringService').from('srv/monitoring-service.cds');

        const adminTx = srv.tx({ user: new cds.User({ id: 'admin', roles: ['SimulatorAdmin'] }) });
        await adminTx.send('resetToCleanSeed');

        const ifaces = await adminTx.run(SELECT.from(srv.entities.Interfaces).where({ active: true }));
        assert.ok(ifaces.length > 0, 'Seed interfaces must exist');
        targetInterfaceId = ifaces[0].ID;
    });

    after(async () => {
        const adminTx = srv.tx({ user: new cds.User({ id: 'admin', roles: ['SimulatorAdmin'] }) });
        await adminTx.send('resetToCleanSeed');
    });

    it('T1 CPI Normal Ingestion: Ingests normal CPI telemetry, stores snapshot, no alert raised', async () => {
        const operatorTx = srv.tx({ user: new cds.User({ id: 'bob', roles: ['SupportOperator'] }) });

        // Emulates payload generated by SentinelTelemetryPusher.groovy during healthy execution
        const cpiPayload = {
            interfaceId: targetInterfaceId,
            capturedAt: new Date().toISOString(),
            pendingCount: 15,
            failedCount: 0,
            retryAttempts: 2,
            successCount: 120,
            oldestPendingAgeSeconds: 20
        };

        const resStr = await operatorTx.send('ingestTelemetry', cpiPayload);
        const res = JSON.parse(resStr);

        assert.equal(res.status, 'Accepted');
        assert.equal(res.alertTriggered, false);
        assert.equal(res.alertAction, 'None');

        // Confirm snapshot in DB
        const snapshots = await operatorTx.run(
            SELECT.from(srv.entities.QueueSnapshots).where({ interface_ID: targetInterfaceId })
        );
        assert.ok(snapshots.length >= 1);
    });

    it('T2 CPI Retry Cascade: Simulates S/4HANA 503 retry cascade and raises EXCESSIVE_RETRIES alert', async () => {
        const operatorTx = srv.tx({ user: new cds.User({ id: 'bob', roles: ['SupportOperator'] }) });

        // Emulates CPI loop execution with backoff retries breaching threshold
        const cpiPayload = {
            interfaceId: targetInterfaceId,
            capturedAt: new Date().toISOString(),
            pendingCount: 280,
            failedCount: 95,
            retryAttempts: 180, // Breaches threshold of 30
            successCount: 2,
            oldestPendingAgeSeconds: 420
        };

        const resStr = await operatorTx.send('ingestTelemetry', cpiPayload);
        const res = JSON.parse(resStr);

        assert.equal(res.status, 'Accepted');
        assert.equal(res.alertTriggered, true);
        assert.equal(res.alertAction, 'Created');
        assert.equal(res.ruleCode, 'EXCESSIVE_RETRIES');
        assert.equal(res.severity, 'Critical');
        assert.equal(res.repeatCount, 1);
    });

    it('T3 CPI Deduplication: Successive telemetry from persistent CPI retries increments repeatCount', async () => {
        const operatorTx = srv.tx({ user: new cds.User({ id: 'bob', roles: ['SupportOperator'] }) });

        const cpiSubsequentPayload = {
            interfaceId: targetInterfaceId,
            capturedAt: new Date().toISOString(),
            pendingCount: 310,
            failedCount: 110,
            retryAttempts: 210,
            successCount: 3,
            oldestPendingAgeSeconds: 480
        };

        const resStr = await operatorTx.send('ingestTelemetry', cpiSubsequentPayload);
        const res = JSON.parse(resStr);

        assert.equal(res.alertTriggered, true);
        assert.equal(res.alertAction, 'Updated');
        assert.equal(res.ruleCode, 'EXCESSIVE_RETRIES');
        assert.equal(res.repeatCount, 2);

        // Verify only one alert record exists in the table for this incident
        const alerts = await operatorTx.run(
            SELECT.from(srv.entities.Alerts).where({ interface_ID: targetInterfaceId, status: 'Open' })
        );
        assert.equal(alerts.length, 1);
        assert.equal(alerts[0].repeatCount, 2);
    });

    it('T4 CPI Validation: Rejects malformed or bounded numeric violations from misconfigured iFlows', async () => {
        const operatorTx = srv.tx({ user: new cds.User({ id: 'bob', roles: ['SupportOperator'] }) });

        const invalidPayload = {
            interfaceId: targetInterfaceId,
            capturedAt: new Date().toISOString(),
            pendingCount: -10, // Invalid negative count
            failedCount: 0,
            retryAttempts: 5,
            successCount: 50,
            oldestPendingAgeSeconds: 10
        };

        await assert.rejects(
            async () => {
                await operatorTx.send('ingestTelemetry', invalidPayload);
            },
            (err) => {
                const code = err.code || err.status;
                assert.equal(code, 400);
                assert.match(err.message, /pendingCount/i);
                return true;
            }
        );
    });
});
